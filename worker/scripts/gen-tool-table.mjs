/**
 * Regenerate the tool table in README.md from the tools themselves.
 *
 * The table used to be hand-maintained, which is how it came to list read_note
 * and read_post for a while after they stopped existing. A doc that describes
 * the surface from outside the surface goes stale silently; this one is derived,
 * and test/run.mjs fails if it drifts.
 *
 * The one-line summary is the first sentence of each tool's description — the
 * same sentence the model reads when deciding whether to call it, so the README
 * cannot claim something different from what the agent is told.
 *
 *   node scripts/gen-tool-table.mjs          rewrite the table
 *   node scripts/gen-tool-table.mjs --check  exit 1 if it would change
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { pathToFileURL } from "node:url";
import { TOOLS, DOMAINS } from "../src/tools.js";

const README = path.resolve(fileURLToPath(import.meta.url), "../../README.md");
const BEGIN = "<!-- TOOLS:BEGIN — generated by scripts/gen-tool-table.mjs, do not edit by hand -->";
const END = "<!-- TOOLS:END -->";

/** First sentence, un-escaped, pipes neutralised so a description cannot break the row. */
function summarise(d) {
  const first = d.replace(/\s+/g, " ").match(/^(.*?[.?!])(\s|$)/);
  return (first ? first[1] : d).replace(/\|/g, "\\|").trim();
}

/**
 * Ordered by domain, not by the order the tools were written in.
 *
 * The source order is archaeology — it records which gap was noticed first. A
 * reader of the README wants the surface grouped by what it is about, and the
 * facets (ADR-0015) are only worth carrying if something is actually read off
 * them. Within a domain, alphabetical: any other rule invites a hand-edit.
 */
export function table() {
  const rows = Object.entries(TOOLS)
    .sort(([an, a], [bn, b]) =>
      DOMAINS.indexOf(a.domain) - DOMAINS.indexOf(b.domain) || an.localeCompare(bn))
    .map(([name, t]) =>
      `| \`${name}\` | ${t.domain} | ${t.class} | ${t.kind} | ${summarise(t.description)} |`);
  return [
    BEGIN, "",
    "| tool | domain | class | kind | answers |",
    "|---|---|---|---|---|",
    ...rows, "", END,
  ].join("\n");
}

// Importing this module must not touch the filesystem — the test suite imports
// table() to compare against the README, and a module that rewrites the file it
// is being checked against always passes.
if (import.meta.url !== pathToFileURL(process.argv[1] ?? "").href) {
  // imported, not run: export table() and stop.
} else main();

function main() {
const src = readFileSync(README, "utf8");
const i = src.indexOf(BEGIN);
const j = src.indexOf(END);
if (i === -1 || j === -1) {
  console.error(`gen-tool-table: no ${BEGIN} / ${END} markers in README.md`);
  process.exit(2);
}
const next = src.slice(0, i) + table() + src.slice(j + END.length);

if (process.argv.includes("--check")) {
  if (next !== src) {
    console.error("gen-tool-table: README.md is out of date — run `node scripts/gen-tool-table.mjs`");
    process.exit(1);
  }
  console.log(`gen-tool-table: README.md matches ${Object.keys(TOOLS).length} tools`);
} else {
  writeFileSync(README, next);
  console.log(`gen-tool-table: wrote ${Object.keys(TOOLS).length} tools into README.md`);
}
}
